def handle_listing_search(params: dict, **kwargs: Any) -> str:
    'Search AU marketplace listings through the local searxng backend and return ranked title, url and snippet hits.\n\nGET the searxng JSON endpoint with the query and format=json; pass limit as the result count, follow items_path to the results array and map each hit to title, url and snippet.'
    # A caller-supplied url wins over the baked default: the tool declared a `url` parameter,
    # so ignoring it makes the smoke test (and any caller) hit a URL nobody asked for.
    base = params.get("url") or 'http://localhost:8888/search'
    if base and "://" not in str(base):
        base = "https://" + str(base).lstrip("/")
    mapping = {'q': '$query', 'format': 'json'}
    defaults = {'query': 'rtx 3060 12gb', 'limit': '10'}
    limit_param = 'limit'
    items_path = 'results'
    fields = {'title': 'title', 'url': 'url', 'snippet': 'content'}
    method = 'GET'

    if not base:
        return json.dumps({"ok": False, "error": "no request url is configured for listing_search"})
    try:
        limit = int(params.get(limit_param or "limit") or defaults.get(limit_param or "limit") or 10)
    except (TypeError, ValueError):
        limit = 10
    limit = max(1, min(limit, 50))

    query = {}
    for key, token in mapping.items():
        value = token
        if isinstance(token, str) and token.startswith("$") and not token.startswith("$env:"):
            value = params.get(token[1:])
            if value in (None, ""):
                value = defaults.get(token[1:], "")
        if value in (None, ""):
            continue
        try:
            query[key] = _token(value)
        except ValueError as exc:
            return json.dumps({"ok": False, "error": str(exc)})

    url = base + ("&" if "?" in base else "?") + urllib.parse.urlencode(query) if query else base
    headers = {"Accept": "application/json",
               "User-Agent": "hermes-plugin/1.0 (+https://hermes-agent.nousresearch.com)"}
    for key, token in {}.items():
        try:
            headers[key] = _token(token)
        except ValueError as exc:
            return json.dumps({"ok": False, "error": str(exc)})
    try:
        request = urllib.request.Request(url, headers=headers, method=method)
        with urllib.request.urlopen(request, timeout=30) as response:
            raw = response.read()[:400000].decode("utf-8", "replace")
    except Exception as exc:
        return json.dumps({"ok": False, "error": f"{type(exc).__name__}: {exc}", "url": url})

    try:
        payload = json.loads(raw)
    except ValueError:
        return json.dumps({"ok": True, "url": url, "text": raw[:4000]})

    items = payload
    for part in [p for p in items_path.split(".") if p]:
        if isinstance(items, dict):
            items = items.get(part)
        else:
            break
    if fields and isinstance(items, list):
        items = [{label: _dig(row, path) for label, path in fields.items()} for row in items[:limit]]
    elif isinstance(items, list):
        items = items[:limit]
    return json.dumps({"ok": True, "url": url,
                       "count": len(items) if isinstance(items, list) else 1,
                       "items": items}, ensure_ascii=False)



def handle_listing_ledger(params: dict, **kwargs: Any) -> str:
    'Read or write the plugin own JSON ledger of GPU deals already reported, so a weekly brief does not re-pitch them.\n\nWhen write is true, overwrite the plugin data file named by path (default seen-listings.json) with the given content string, creating it if absent, and report the number of bytes stored. When write is false or omitted, read that same file and return its raw JSON text, or an empty ledger object if th'
    root = _data_dir()
    raw = params.get("path") or 'seen-listings.json'
    if not raw:
        return json.dumps({"ok": False, "error": "no path is configured for listing_ledger"})
    target = Path(os.path.expanduser(str(raw)))
    if not target.is_absolute():
        target = root / target
    root.mkdir(parents=True, exist_ok=True)
    try:
        target = target.resolve()
        target.relative_to(root.resolve())
    except ValueError:
        return json.dumps({"ok": False,
                           "error": f"{target} is outside this plugin's data dir ({root}) — "
                                    "a generated file tool only touches its own files"})
    try:
        if params.get("write"):
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(str(params.get("content") or ""), encoding="utf-8")
            return json.dumps({"ok": True, "path": str(target), "bytes": target.stat().st_size})
        return json.dumps({"ok": True, "path": str(target),
                           "text": target.read_text(encoding="utf-8", errors="replace")[:20000]},
                          ensure_ascii=False)
    except Exception as exc:
        return json.dumps({"ok": False, "error": f"{type(exc).__name__}: {exc}"})


